const root = resolve(__dirname, "..");
const crew = join(root, "dist", "crew.js");

function baseMsg(extra) {
  return {
    ts: new Date().toISOString(),
    from: "sender-session-id",
    fromShort: "sender01",
    fromCwd: "/tmp/sender",
    text: "coordinate first",
    expiresAt: new Date(Date.now() + 3_600_000).toISOString(),
    ...extra,
  };
}

function inboxDir(env, sid) {
  return join(env.CREW_INBOX_ROOT, sid);
}

/** Inboxes written by crew <= 0.3.x, still drained during migration. */
function legacyInboxDir(env, sid, era) {
  return era === "0.2"
    ? join(env.CLAUDE_HOME, "crew", "inbox", sid)
    : join(env.CREW_HOME, "inbox", sid);
}

function dropMessage(dir, msg) {
  mkdirSync(dir, { recursive: true });
  const name = `${Date.now()}-${Math.random().toString(16).slice(2, 10)}.json`;
  writeFileSync(join(dir, name), JSON.stringify(msg));
}

function writeInbox(env, sid, msg) {
  dropMessage(inboxDir(env, sid), msg);
}

function pendingFiles(dir) {
  try {
    return readdirSync(dir).filter((f) => f.endsWith(".json"));
  } catch {
    return [];
  }
}

/** A live session record, as the hooks would have registered it. */
function registerSession(env, sid, pid, extra) {
  mkdirSync(join(env.CREW_HOME, "sessions"), { recursive: true });
  writeFileSync(
    join(env.CREW_HOME, "sessions", `${sid}.json`),
    JSON.stringify({
      pid,
      sessionId: sid,
      agent: "claude",
      status: "idle",
      cwd: "/tmp/work",
      startedAt: new Date().toISOString(),
      lastSeen: new Date().toISOString(),
      transcript: null,
      ...extra,
    }),
  );
}

/** A process that stays alive so liveness pruning keeps the record. */
function sleeper(t) {
  const child = spawn(process.execPath, ["-e", "setInterval(() => {}, 1e9)"], {
    stdio: "ignore",
  });
  t.after(() => child.kill());
  return child;
}

function runAsync(args, env, input) {
  return new Promise((done) => {
    const child = spawn(process.execPath, [crew, ...args], {
      cwd: root,
      env,
      stdio: ["pipe", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (c) => (stdout += c));
    child.stderr.on("data", (c) => (stderr += c));
    child.on("close", (status) => done({ status, stdout, stderr }));
    child.stdin.end(input);
  });
}

function stopHook(env, sid, event = "Stop") {
  return run(
    ["--hook"],
    env,
    JSON.stringify({
      session_id: sid,
      hook_event_name: event,
      transcript_path: null,
      cwd: root,
    }),
  );
}

function homes() {
  const root = mkdtempSync(join(tmpdir(), "crew-test-"));
  const env = {
    ...process.env,
    CLAUDE_HOME: join(root, "claude"),
    CODEX_HOME: join(root, "codex"),
    CREW_HOME: join(root, "crew"),
    CREW_INBOX_ROOT: join(root, "inbox"), // never the real /tmp/crew-<uid>

    XDG_CONFIG_HOME: join(root, "xdg-config"), // OpenCode plugin location
    XDG_DATA_HOME: join(root, "xdg-data"), // OpenCode sqlite location
  };
  // The OpenCode plugin's own env identification must not leak between tests.
  delete env.CREW_AGENT;
  delete env.CREW_PID;
  delete env.CREW_SESSION_ID;
  return { root, env };
}

function run(args, env, input) {
  return spawnSync(process.execPath, [crew, ...args], {
    cwd: root,
    env,
    input,
    encoding: "utf8",
  });
}

test("install-hook merges all products and uninstall preserves other settings", () => {
  const h = homes();
  mkdirSync(h.env.CLAUDE_HOME, { recursive: true });
  writeFileSync(
    join(h.env.CLAUDE_HOME, "settings.json"),
    JSON.stringify({ theme: "dark" }),
  );

  assert.equal(run(["install-hook"], h.env).status, 0);
  for (const path of [
    join(h.env.CLAUDE_HOME, "settings.json"),
    join(h.env.CODEX_HOME, "hooks.json"),
  ]) {
    const config = JSON.parse(readFileSync(path, "utf8"));
    for (const event of ["SessionStart", "UserPromptSubmit", "PostToolUse", "Stop"]) {
      assert.equal(config.hooks[event][0].hooks[0].command, "crew --hook");
    }
  }
  assert.equal(
    JSON.parse(readFileSync(join(h.env.CLAUDE_HOME, "settings.json"), "utf8")).theme,
    "dark",
  );
  const plugin = join(h.env.XDG_CONFIG_HOME, "opencode", "plugins", "crew.js");
  const source = readFileSync(plugin, "utf8");
  assert.match(source, /generated by @0xmmo\/crew/);
  assert.ok(source.includes(JSON.stringify(join(root, "dist", "crew.js"))));

  assert.equal(run(["uninstall-hook"], h.env).status, 0);
  const remaining = JSON.parse(
    readFileSync(join(h.env.CLAUDE_HOME, "settings.json"), "utf8"),
  );
  assert.deepEqual(remaining, { theme: "dark" });
  assert.equal(existsSync(plugin), false);

  // A plugin file crew didn't generate is never overwritten or removed.
  writeFileSync(plugin, "export const Mine = async () => ({})");
  const refused = run(["install-hook"], h.env);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /refusing to overwrite/);
  assert.equal(run(["uninstall-hook"], h.env).status, 0);
  assert.equal(existsSync(plugin), true);
});

