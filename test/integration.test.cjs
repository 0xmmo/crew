test("doctor flags a stale OpenCode plugin, a foreign one, and unreadable settings", () => {
  const h = homes();
  assert.equal(run(["install-hook"], h.env).status, 0);

  // An older crew stamped a different version (or none at all).
  const plugin = join(h.env.XDG_CONFIG_HOME, "opencode", "plugins", "crew.js");
  const source = readFileSync(plugin, "utf8");
  writeFileSync(plugin, source.replace(/^\/\/ crew \S+ — /, "// crew 0.3.0 — "));
  let r = JSON.parse(run(["doctor", "--json"], h.env).stdout);
  let oc = r.checks.find((c) => c.id === "hook:opencode");
  assert.equal(oc.status, "warn");
  assert.match(oc.detail, /older crew/);
  // --fix re-renders it; a plugin crew didn't write is left alone.
  assert.equal(run(["doctor", "--fix"], h.env).status, 0);
  assert.equal(readFileSync(plugin, "utf8"), source);
  writeFileSync(plugin, "export const Mine = async () => ({})");
  r = JSON.parse(run(["doctor", "--fix", "--json"], h.env).stdout);
  oc = r.checks.find((c) => c.id === "hook:opencode");
  assert.equal(oc.status, "fail");
  assert.match(oc.detail, /crew didn't generate it/);
  assert.equal(readFileSync(plugin, "utf8"), "export const Mine = async () => ({})");

  // Broken JSON is reported, never overwritten, even under --fix.
  const settings = join(h.env.CLAUDE_HOME, "settings.json");
  writeFileSync(settings, "{ not json");
  r = JSON.parse(run(["doctor", "--fix", "--json"], h.env).stdout);
  const claude = r.checks.find((c) => c.id === "hook:claude");
  assert.equal(claude.status, "fail");
  assert.match(claude.detail, /isn't valid JSON/);
  assert.equal(readFileSync(settings, "utf8"), "{ not json");
});

test("doctor refuses a mailbox it doesn't own and counts stale registry entries", async (t) => {
  const h = homes();
  // A symlink where the mailbox root should be: fail, and --fix must not follow it.
  const elsewhere = mkdtempSync(join(tmpdir(), "crew-elsewhere-"));
  symlinkSync(elsewhere, h.env.CREW_INBOX_ROOT);
  let r = JSON.parse(run(["doctor", "--fix", "--json"], h.env).stdout);
  const mailbox = r.checks.find((c) => c.id === "mailbox");
  assert.equal(mailbox.status, "fail");
  assert.match(mailbox.detail, /symlink/);
  assert.equal(lstatSync(h.env.CREW_INBOX_ROOT).isSymbolicLink(), true);
  rmSync(h.env.CREW_INBOX_ROOT);

  // Too-open perms are a warning that --fix tightens.
  mkdirSync(h.env.CREW_INBOX_ROOT, { recursive: true, mode: 0o755 });
  r = JSON.parse(run(["doctor", "--json"], h.env).stdout);
  assert.equal(r.checks.find((c) => c.id === "mailbox").status, "warn");
  r = JSON.parse(run(["doctor", "--fix", "--json"], h.env).stdout);
  assert.equal(r.checks.find((c) => c.id === "mailbox").status, "fixed");
  assert.equal(lstatSync(h.env.CREW_INBOX_ROOT).mode & 0o077, 0);

  // One live session, one whose process is gone.
  const alive = sleeper(t);
  registerSession(h.env, "live-session", alive.pid);
  registerSession(h.env, "dead-session", 2 ** 22 - 1);
  r = JSON.parse(run(["doctor", "--json"], h.env).stdout);
  let registry = r.checks.find((c) => c.id === "registry");
  assert.equal(registry.status, "warn");
  assert.match(registry.detail, /1 live, 1 stale/);
  r = JSON.parse(run(["doctor", "--fix", "--json"], h.env).stdout);
  registry = r.checks.find((c) => c.id === "registry");
  assert.equal(registry.status, "fixed");
  assert.equal(existsSync(join(h.env.CREW_HOME, "sessions", "dead-session.json")), false);
  assert.equal(existsSync(join(h.env.CREW_HOME, "sessions", "live-session.json")), true);
});
